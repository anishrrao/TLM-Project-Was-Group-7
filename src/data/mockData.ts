// 30-Day Demand Forecast dataset (November 2026 Simulation baseline, during upcoming Karthika Deepotsava)
export const GENERATE_30_DAY_FORECAST = (): DayForecast[] => {
  const days: DayForecast[] = [];
  const weekdays = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
  
  // Starting Nov 9, 2026
  for (let i = 0; i < 30; i++) {
    const d = new Date(2026, 10, 9 + i);
    const dayOfWeek = weekdays[d.getDay() === 0 ? 6 : d.getDay() - 1];
    const isWeekend = dayOfWeek === 'Friday' || dayOfWeek === 'Saturday' || dayOfWeek === 'Sunday';
    
    // Festival period: Karthika Deepotsava starts on Nov 21 - Nov 25 (Day 12-16)
    const isFestival = i >= 12 && i <= 16;
    const festivalName = isFestival ? 'Karthika Deepotsava & Laksha Deepotsava' : undefined;

    // Noticeable 2026 festival slump evidence:
    // 2024 Karthika festival had H = 94%
    // 2025 Karthika festival had H = 90%
    // 2026 current booking pace B is lagging significantly (only 48% vs 85% at this stage!)
    const historicalOccupancy = isFestival ? 92 : isWeekend ? 62 : 36;
    const weekdayAvgOccupancy = isWeekend ? 58 : 34;
    const bookingPaceEstimate = isFestival ? 58 : isWeekend ? 50 : 28; // Lagging pace in 2026!
    const calendarDemandEstimate = isFestival ? 95 : isWeekend ? 65 : 30;

    const forecast = calculateDemandForecast(
      historicalOccupancy,
      weekdayAvgOccupancy,
      bookingPaceEstimate,
      calendarDemandEstimate
    );

    const occupiedRooms = Math.min(40, Math.round((forecast / 100) * 40));
    const availableRooms = 40 - occupiedRooms;
    const expectedGuests = Math.round(occupiedRooms * 2.3);
    const bookingPaceMultiplier = isFestival ? 0.78 : isWeekend ? 0.95 : 0.88; // -22% pace for festival

    days.push({
      date: d.toISOString().split('T')[0],
      dayOfWeek,
      isFestival,
      festivalName,
      historicalOccupancy,
      weekdayAvgOccupancy,
      bookingPaceEstimate,
      calendarDemandEstimate,
      forecastOccupancy: forecast,
      occupiedRooms,
      availableRooms,
      expectedGuests,
      bookingPaceMultiplier,
      status: forecast > 75 ? 'Surge' : forecast < 40 ? 'Low' : 'Normal',
    });
  }

  return days;
};

